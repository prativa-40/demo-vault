from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED

from reportlab.lib.colors import HexColor, black, white
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfbase.pdfmetrics import stringWidth
from reportlab.pdfgen.canvas import Canvas

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs" / "dummy-identity-documents"
OUT.mkdir(parents=True, exist_ok=True)

PEOPLE = [
    ("Ramesh Sharma", "1971-05-10", "Male", "RAMESH", "55"),
    ("Monica Sharma", "1976-03-18", "Female", "MONICA", "50"),
    ("Chaitra Sharma", "2001-04-12", "Female", "CHAITRA", "25"),
    ("Ankur Sharma", "2006-02-08", "Male", "ANKUR", "20"),
]

DOCS = ["Aadhaar", "Passport", "Voter ID", "PAN Card", "Driving Licence"]


def friendly_date(iso):
    y, m, d = iso.split("-")
    return f"{d}/{m}/{y}"


def fields(document, name, dob, gender, key, age):
    address = "Demo Address, Test City, Karnataka 560000"
    if document == "Aadhaar":
        return [
            ("Government of India", ""),
            (name, ""),
            ("DOB", friendly_date(dob)),
            ("Gender", gender),
            ("Aadhaar Number", f"0000 0000 00{age}"),
            ("Address", address),
        ]
    if document == "Passport":
        return [("Name", name), ("Passport Number", f"TEST-{key}-{age}"), ("Date of Birth", friendly_date(dob)), ("Date of Expiry", "09/05/2031"), ("Address", address)]
    if document == "Voter ID":
        return [("Name", name), ("Voter ID Number", f"TEST-VOTER-{key[0]}{age}"), ("Date of Birth", friendly_date(dob)), ("Address", address)]
    if document == "PAN Card":
        return [("Name", name), ("PAN Number", f"TEST-PAN-{key[0]}{age}"), ("Date of Birth", friendly_date(dob))]
    return [("Name", name), ("Licence Number", f"TEST-DL-{key[0]}{age}"), ("Date of Birth", friendly_date(dob)), ("Expiry Date", "09/05/2031"), ("RTO / Issuing Authority", "Demo RTO"), ("Address", address)]


def draw_document(path, document, name, dob, gender, key, age):
    canvas = Canvas(str(path), pagesize=A4)
    width, height = A4
    accent = {"Aadhaar": "#9B2C2C", "Passport": "#193A70", "Voter ID": "#70501D", "PAN Card": "#40583A", "Driving Licence": "#4C3A74"}[document]
    canvas.setFillColor(HexColor("#F7F9F8"))
    canvas.rect(0, 0, width, height, fill=1, stroke=0)
    canvas.setFillColor(HexColor(accent))
    canvas.rect(0, height - 45 * mm, width, 45 * mm, fill=1, stroke=0)
    canvas.setFillColor(white)
    canvas.setFont("Helvetica-Bold", 22)
    canvas.drawString(20 * mm, height - 21 * mm, document.upper())
    canvas.setFont("Helvetica-Bold", 10)
    canvas.drawString(20 * mm, height - 29 * mm, "SAMPLE DOCUMENT FOR PRODUCT TESTING")
    canvas.setFont("Helvetica", 8)
    canvas.drawString(20 * mm, height - 35 * mm, "Fictional data only - not a government-issued identity document")
    canvas.setFillColor(HexColor("#D93B3B"))
    canvas.setFont("Helvetica-Bold", 17)
    watermark = "TEST DOCUMENT - NOT VALID"
    canvas.drawCentredString(width / 2, height - 59 * mm, watermark)
    canvas.setStrokeColor(HexColor("#D9E2DE"))
    canvas.setLineWidth(1)
    canvas.roundRect(20 * mm, 48 * mm, width - 40 * mm, height - 125 * mm, 4 * mm, fill=0, stroke=1)
    y = height - 78 * mm
    for label, value in fields(document, name, dob, gender, key, age):
        if not value:
            canvas.setFillColor(black)
            canvas.setFont("Helvetica-Bold", 15)
            canvas.drawString(32 * mm, y, label)
            y -= 16 * mm
            continue
        canvas.setFillColor(HexColor("#64736D"))
        canvas.setFont("Helvetica-Bold", 8)
        canvas.drawString(32 * mm, y, label.upper())
        canvas.setFillColor(black)
        canvas.setFont("Helvetica", 13)
        canvas.drawString(32 * mm, y - 7 * mm, value)
        y -= 22 * mm
    canvas.setFillColor(HexColor("#64736D"))
    canvas.setFont("Helvetica", 8)
    canvas.drawString(20 * mm, 30 * mm, "Generated by Hearth test-data generator | This file contains no real identity information.")
    canvas.save()


created = []
for name, dob, gender, key, age in PEOPLE:
    compact = name.replace(" ", "")
    for document in DOCS:
        filename = f"{compact}_{document.replace(' ', '')}_Test.pdf"
        destination = OUT / filename
        draw_document(destination, document, name, dob, gender, key, age)
        created.append(destination)

readme = OUT / "README.txt"
readme.write_text(
    "20 fictional sample identity documents for Hearth testing.\n\n"
    "Each PDF is clearly marked TEST DOCUMENT - NOT VALID. Upload it from the matching family's identity record, then use Open scan and Re-read to test the product.\n",
    encoding="utf-8",
)
created.append(readme)

archive = ROOT / "outputs" / "dummy-identity-documents.zip"
with ZipFile(archive, "w", ZIP_DEFLATED) as bundle:
    for item in created:
        bundle.write(item, item.relative_to(OUT.parent))

print(f"Created {len(created) - 1} sample PDFs in {OUT}")
print(f"Created archive {archive}")
